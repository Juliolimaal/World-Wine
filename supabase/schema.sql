-- World Wines: catalog used by src/app/services/wine.service.ts
-- Run this script in Supabase > SQL Editor.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null unique,
  subtitle text not null default '',
  description text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  category text not null check (category in ('red', 'white', 'rose')),
  image text not null default '',
  region text not null default '',
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

grant select, insert, delete on public.products to anon, authenticated;
grant usage, select on sequence public.products_id_seq to anon, authenticated;

drop policy if exists "products can be read publicly" on public.products;
create policy "products can be read publicly"
  on public.products for select
  to anon, authenticated
  using (true);

-- The current Angular project does not have user sign-in, so these two policies
-- make its catalog form work with the Supabase anon key for a classroom demo.
-- Anyone who has the app URL and anon key can add or delete catalog rows.
drop policy if exists "demo users can add products" on public.products;
create policy "demo users can add products"
  on public.products for insert
  to anon, authenticated
  with check (true);

drop policy if exists "demo users can delete products" on public.products;
create policy "demo users can delete products"
  on public.products for delete
  to anon, authenticated
  using (true);

